// Release signing is loaded from a local, git-ignored keystore.properties file so that no
// secrets ever live in source control. See keystore.properties.example for the expected
// format. If the file is absent (e.g. on a fresh checkout or CI without secrets), the
// release build type simply falls back to being unsigned so the project still compiles.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        load(FileInputStream(keystorePropertiesFile))
    }
}

